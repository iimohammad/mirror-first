#!/bin/sh
# ---------------------------------------------------------------------------
# certbot در کانتینر جدا هر ۱۲ ساعت گواهی را renew می‌کند، ولی nginx گواهی را
# در حافظه نگه می‌دارد و خودش متوجه فایل جدید نمی‌شود. بدون این حلقه، گواهی
# تمدید می‌شود اما کاربر همچنان گواهی منقضی می‌بیند تا وقتی دستی restart کنی.
#
# entrypoint ایمیج رسمی nginx هر فایل اجرایی داخل /docker-entrypoint.d را
# قبل از بالا آمدن nginx اجرا می‌کند؛ ما یک حلقه‌ی پس‌زمینه جا می‌گذاریم.
# ---------------------------------------------------------------------------
( while :; do
    sleep 12h
    nginx -s reload 2>/dev/null || true
  done ) &
